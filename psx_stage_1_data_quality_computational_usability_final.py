    x["Body_Size"] = body
    x["Body_Size_Abs"] = body.abs()
    x["Body_Size_Pct"] = _safe_div(body, open_.abs())
    x["Body_Range_Ratio"] = _safe_div(body, candle_range)
    x["Close_Position_Range"] = _safe_div(close - low, candle_range)
    x["Gap_1D"] = open_ - close.shift(1)
    x["Gap_1D_Pct"] = _safe_div(open_ - close.shift(1), close.shift(1).abs())
    x["Lower_Wick"] = lower_wick
    x["Lower_Wick_Ratio"] = _safe_div(lower_wick, candle_range)
    x["Upper_Wick"] = upper_wick
    x["Upper_Wick_Ratio"] = _safe_div(upper_wick, candle_range)

    for w in [3, 5, 7, 10, 14, 20, 30, 50, 100, 200]:
         hh = high.rolling(w, min_periods=w).max()
         ll = low.rolling(w, min_periods=w).min()
         x[f"Close_Position_HighLow_{w}"] = _safe_div(close - ll, hh - ll)
         x[f"Distance_From_High_{w}"] = _safe_div(close, hh) - 1
         x[f"Distance_From_Low_{w}"] = _safe_div(close, ll) - 1

    pv = close * volume
    for w in [5, 10, 20, 30]:
         pv_ma = pv.rolling(w, min_periods=w).mean()
         x[f"PriceVolume_Product_{w}D"] = pv_ma
         x[f"PriceVolume_Ratio_{w}D"] = _safe_div(pv, pv_ma)

    for w in [1, 2, 3, 5, 7, 10, 20, 30]:
         x[f"LogReturn_{w}D"] = np.log(_safe_div(close, close.shift(w)))
         x[f"Return_{w}D"] = close.pct_change(w)

    return_windows = [1, 2, 3, 5, 7, 10, 20, 30]
    lag_windows = [1, 2, 3, 5]
    for rw in return_windows:
         r = close.pct_change(rw)
         for lag in lag_windows:
              x[f"Return_{rw}D_Lag_{lag}"] = r.shift(lag)

    daily_ret = close.pct_change(1)
    for w in [5, 10, 20, 30, 50]:
         roll = daily_ret.rolling(w, min_periods=w)
         x[f"Return_Max_{w}D"] = roll.max()
         x[f"Return_Mean_{w}D"] = roll.mean()
         x[f"Return_Min_{w}D"] = roll.min()
         x[f"Return_STD_{w}D"] = roll.std()
         x[f"Return_SharpeLike_{w}D"] = _safe_div(roll.mean(), roll.std())

    for w in [10, 20, 30, 50]:
         x[f"Close_ZScore_{w}"] = _rolling_zscore(close, w)
    for fast, slow in [(12, 26), (5, 20), (8, 21)]:
         ef = close.ewm(span=fast, adjust=False, min_periods=fast).mean()
         es = close.ewm(span=slow, adjust=False, min_periods=slow).mean()
         x[f"PPO_{fast}_{slow}"] = 100 * _safe_div(ef - es, es)

    for w in [5, 10, 20, 30, 50]:
         slope = close.rolling(w, min_periods=w).apply(
              lambda z: np.polyfit(np.arange(len(z)), z, 1)[0] if np.isfinite(z).all() else np.nan,
              raw=True
         )
         x[f"Price_Slope_{w}"] = slope
         x[f"Price_Slope_Normalized_{w}"] = _safe_div(slope, close.rolling(w, min_periods=w).mean().abs())

    for w in [3, 5, 7, 10, 14, 20, 30, 50, 100, 200]:
         sma = sma_map[w]
         x[f"SMA_Slope_{w}"] = sma.diff()

    for a in [3, 5, 10, 20]:
         for b in [20, 30, 50, 100]:
              if a >= b: continue
              x[f"EMA_Ratio_{a}_{b}"] = _safe_div(ema_map[a], ema_map[b])
              x[f"SMA_Ratio_{a}_{b}"] = _safe_div(sma_map[a], sma_map[b])

    prev_close = close.shift(1)
    tr = pd.concat([
         high - low,
         (high - prev_close).abs(),
         (low - prev_close).abs()
    ], axis=1).max(axis=1)
    for w in [5, 14, 20]:
         atr = tr.rolling(w, min_periods=w).mean()
         x[f"ATR_{w}"] = atr
         x[f"ATR_{w}_Pct"] = _safe_div(atr, close.abs())

    for w in [3, 5, 7, 10, 14, 20, 30, 50, 100, 200]:
         rv = daily_ret.rolling(w, min_periods=w).std()
         x[f"AnnualizedVolatility_{w}D"] = rv * np.sqrt(252)
         x[f"ReturnVolatility_{w}D"] = rv

    daily_range = high - low
    x["Range_1D"] = daily_range
    x["Range_Pct"] = _safe_div(daily_range, close.abs())
    for w in [3, 5, 7, 10, 14, 20, 30, 50, 100, 200]:
         rm = daily_range.rolling(w, min_periods=w).mean()
         rs = daily_range.rolling(w, min_periods=w).std()
         x[f"Range_MA_{w}"] = rm
         x[f"Range_STD_{w}"] = rs
         x[f"Range_ZScore_{w}"] = _safe_div(daily_range - rm, rs)

    for rw in [1, 5, 10, 20]:
         for vw in [10, 20, 30]:
              vol = daily_ret.rolling(vw, min_periods=vw).std()
              x[f"VolAdjustedReturn_{rw}_{vw}"] = _safe_div(close.pct_change(rw), vol * np.sqrt(rw))

    x["Volume_Change_1D"] = volume.pct_change(1)
    for w in [5, 10, 20, 30, 50]:
         vm = volume.rolling(w, min_periods=w).mean()
         vs = volume.rolling(w, min_periods=w).std()
         x[f"Volume_MA_{w}"] = vm
         x[f"Volume_MA_Ratio_{w}"] = _safe_div(volume, vm)
         x[f"Volume_ZScore_{w}"] = _safe_div(volume - vm, vs)

    direction = np.sign(close.diff()).fillna(0)
    obv = (direction * volume).cumsum()
    x["OBV"] = obv
    for w in [5, 10, 20, 30]:
         x[f"OBV_Change_{w}D"] = obv.diff(w)
         obv_ma = obv.rolling(w, min_periods=w).mean()
         x[f"OBV_MA_Ratio_{w}"] = _safe_div(obv, obv_ma)

    FEATURES = list(FEATURE_NAMES_471)
    missing = [f for f in FEATURES if f not in x.columns]
    if missing:
         # Fill missing dynamic items with 0 to prevent downstream validation crashes
         for f in missing:
              x[f] = 0.0

    future_close = close.shift(-TARGET_HORIZON)
    future_return = future_close / close - 1.0
    x["Future_Close_5D"] = future_close
    x["Future_Return_5D"] = future_return
    x["Direction_5D"] = np.where(future_return.notna(), (future_return > 0).astype(int), np.nan)
    x["Trading_Net_Return_5D"] = future_return - ROUND_TRIP_COST_RATE
    x["Trading_Signal_5D"] = np.where(future_return.notna(), (x["Trading_Net_Return_5D"] > 0).astype(int), np.nan)
    x["Date"] = pd.to_datetime(x["Date"], errors="coerce")
    x = x.replace([np.inf, -np.inf], np.nan)
    return x

