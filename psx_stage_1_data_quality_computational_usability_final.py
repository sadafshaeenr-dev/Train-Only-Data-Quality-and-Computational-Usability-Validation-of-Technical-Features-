def create_features(df):
    x = df.copy()
    for c in ["Open", "High", "Low", "Close", "Adj Close", "Volume"]:
        if c in x.columns:
            x[c] = clean_numeric(x[c])

    close = x["Close"]
    high = x["High"]
    low = x["Low"]
    open_ = x["Open"]
    volume = x["Volume"]
    eps = 1e-12

    for w in [10, 20, 30]:
        mid = close.rolling(w, min_periods=w).mean()
        sd = close.rolling(w, min_periods=w).std()
        upper = mid + 2 * sd
        lower = mid - 2 * sd
        x[f"BB_Lower_{w}"] = lower
        x[f"BB_Middle_{w}"] = mid
        x[f"BB_Upper_{w}"] = upper
        x[f"BB_Width_{w}"] = _safe_div(upper - lower, mid.abs())
        x[f"BB_Position_{w}"] = _safe_div(close - lower, upper - lower)

    for w in [5, 10, 20, 30, 50]:
        prior_high = high.shift(1).rolling(w, min_periods=w).max()
        prior_low = low.shift(1).rolling(w, min_periods=w).min()
        tag = f"{w}D"
        x[f"Breakout_Up_{tag}"] = (close > prior_high).astype(float)
        x[f"Breakout_Down_{tag}"] = (close < prior_low).astype(float)
        x[f"High_Breakout_Distance_{tag}"] = _safe_div(close, prior_high) - 1
        x[f"Low_Breakout_Distance_{tag}"] = _safe_div(close, prior_low) - 1

    for w in [1, 3, 5, 10, 20]:
        r = close.pct_change(w)
        x[f"Negative_Return_Flag_{w}D"] = (r < 0).astype(float)
        x[f"Positive_Return_Flag_{w}D"] = (r > 0).astype(float)

    ema_map = {}
    for w in [3, 5, 7, 10, 14, 20, 30, 50, 100, 200]:
        ema = close.ewm(span=w, adjust=False, min_periods=w).mean()
        ema_map[w] = ema
        x[f"EMA_{w}"] = ema
        x[f"Close_EMA_Distance_{w}"] = close - ema
        x[f"Close_EMA_Ratio_{w}"] = _safe_div(close, ema)

    rsi_map = {w: _rsi(close, w) for w in [7, 14, 21]}
    for rw in [7, 14, 21]:
        for tw in [10, 20, 50]:
            x[f"RSI_{rw}_TrendRatio_{tw}"] = _safe_div(rsi_map[rw], rsi_map[rw].rolling(tw, min_periods=tw).mean())

    for col in ["Close", "High", "Low", "Open", "Volume"]:
        s = x[col]
        for lag in [1, 2, 3, 5, 7, 10, 20]:
            x[f"{col}_Lag_{lag}"] = s.shift(lag)

    for fast, slow in [(12, 26), (5, 20), (8, 21)]:
         line, sig, hist = _macd(close, fast, slow, 9)
         base = f"MACD_{fast}_{slow}_9"
         x[base] = line
         x[f"{base}_Signal"] = sig
         x[f"{base}_Histogram"] = hist
         x[f"{base}_PctPrice"] = _safe_div(line, close.abs())

    for w in [3, 5, 7, 10, 14, 20]:
         x[f"Momentum_{w}D"] = close - close.shift(w)
         x[f"ROC_{w}D"] = close.pct_change(w)

    for w in [7, 14, 21]:
         r = rsi_map[w]
         x[f"RSI_{w}"] = r
         x[f"RSI_{w}_Centered"] = r - 50
         x[f"RSI_{w}_Change_1D"] = r.diff(1)
         x[f"RSI_{w}_MA_3"] = r.rolling(3, min_periods=3).mean()

    for w in [5, 14, 21, 7]:
         k, d = _stoch(high, low, close, w)
         x[f"StochK_{w}"] = k
         x[f"StochD_{w}"] = d
         x[f"Stoch_KD_Diff_{w}"] = k - d
         hh = high.rolling(w, min_periods=w).max()
         ll = low.rolling(w, min_periods=w).min()
