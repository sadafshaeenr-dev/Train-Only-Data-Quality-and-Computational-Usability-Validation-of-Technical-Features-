def block_bootstrap_indices(n, block_len, reps, rng):
    if n <= 0: return []
    block_len=max(1,min(int(block_len),n)); out=[]
    for _ in range(reps):
        ids=[]
        while len(ids)<n:
            start=int(rng.integers(0,n-block_len+1))
            ids.extend(range(start,start+block_len))
        out.append(np.asarray(ids[:n],dtype=int))
    return out

def psi_score(expected, actual, bins=10):
    a=pd.Series(expected).replace([np.inf,-np.inf],np.nan).dropna().astype(float)
    b=pd.Series(actual).replace([np.inf,-np.inf],np.nan).dropna().astype(float)
    if len(a)<50 or len(b)<50 or a.nunique()<2: return np.nan
    edges=np.unique(np.quantile(a,np.linspace(0,1,bins+1)))
    if len(edges)<3: return np.nan
    edges[0],edges[-1]=-np.inf,np.inf
    ca=np.histogram(a,bins=edges)[0]/len(a); cb=np.histogram(b,bins=edges)[0]/len(b)
    ca=np.clip(ca,1e-6,None); cb=np.clip(cb,1e-6,None)
    return float(np.sum((cb-ca)*np.log(cb/ca)))

def pt_pvalue(x, y, min_n=80):
    """Pesaran-Timmermann directional test using sign of prior feature change as forecast."""
    z=pd.DataFrame({"x":pd.Series(x).reset_index(drop=True),"y":pd.Series(y).reset_index(drop=True)})
    z=z.replace([np.inf,-np.inf],np.nan).dropna()
    if len(z)<min_n: return np.nan
    pred=(z.x.diff()>0).iloc[1:].astype(int).to_numpy()
    actual=(z.y.iloc[1:]>0).astype(int).to_numpy()
    n=len(actual)
    if n<min_n or len(np.unique(pred))<2 or len(np.unique(actual))<2: return np.nan
    p=float(actual.mean()); q=float(pred.mean()); p11=float(np.mean((pred==1)&(actual==1)))
    pstar=p*q+(1-p)*(1-q)
    variance=max(p*q*(1-p)*(1-q)/n,1e-12)
    zstat=(p11-pstar)/math.sqrt(variance)
    return float(2*(1-norm.cdf(abs(zstat))))

def adwin_count(values, delta=0.01):
    try:
        from river.drift import ADWIN
        detector=ADWIN(delta=float(delta))
        s=pd.Series(values).replace([np.inf,-np.inf],np.nan).dropna().astype(float)
        if len(s)<100: return np.nan
        med=float(s.median()); mad=float((s-med).abs().median())
        scale=1.4826*mad if mad>1e-12 else float(s.std())
        if not np.isfinite(scale) or scale<=1e-12: return np.nan
        count=0
        for v in ((s-med)/scale).to_numpy():
            detector.update(float(v))
            if detector.drift_detected: count+=1
        return int(count)
    except Exception:
        return np.nan

def structural_break_pvalue(values):
    s=pd.Series(values).replace([np.inf,-np.inf],np.nan).dropna().astype(float)
    if len(s)<100 or s.nunique()<3: return np.nan
    resid=(s-s.mean()).to_numpy()
    try: return float(breaks_cusumolsresid(resid, ddof=1)[1])
    except Exception: return np.nan

def adversarial_auc(values):
    """AUC of a one-feature early/late-period discriminator, entirely within TRAIN."""
    s=pd.Series(values).replace([np.inf,-np.inf],np.nan).dropna().astype(float).reset_index(drop=True)
    if len(s)<120 or s.nunique()<3: return np.nan
    cut=len(s)//2; y=np.r_[np.zeros(cut,dtype=int),np.ones(len(s)-cut,dtype=int)]
    try:
        auc=float(roc_auc_score(y, rankdata(s.to_numpy())))
        return max(auc,1.0-auc)
    except Exception: return np.nan

def _safe_div(a, b):
    return a / b.replace(0, np.nan)

def _rolling_zscore(s, w):
    m = s.rolling(w, min_periods=w).mean()
    sd = s.rolling(w, min_periods=w).std()
    return _safe_div(s - m, sd)

def _macd(close, fast, slow, signal=9):
    ef = close.ewm(span=fast, adjust=False, min_periods=fast).mean()
    es = close.ewm(span=slow, adjust=False, min_periods=slow).mean()
    line = ef - es
    sig = line.ewm(span=signal, adjust=False, min_periods=signal).mean()
    hist = line - sig
    return line, sig, hist

def _rsi(close, period):
    delta = close.diff()
    gain = delta.clip(lower=0).rolling(period, min_periods=period).mean()
    loss = (-delta.clip(upper=0)).rolling(period, min_periods=period).mean()
    rs = _safe_div(gain, loss)
    return 100 - 100 / (1 + rs)

def _stoch(high, low, close, period):
    ll = low.rolling(period, min_periods=period).min()
    hh = high.rolling(period, min_periods=period).max()
    k = 100 * _safe_div(close - ll, hh - ll)
    d = k.rolling(3, min_periods=3).mean()
    return k, d

