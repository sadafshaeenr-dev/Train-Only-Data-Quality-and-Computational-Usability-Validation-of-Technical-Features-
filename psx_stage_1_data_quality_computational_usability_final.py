def safe_spearman(x, y, min_n=60):
    z = pd.concat([pd.Series(x).reset_index(drop=True), pd.Series(y).reset_index(drop=True)], axis=1)
    z = z.replace([np.inf, -np.inf], np.nan).dropna()
    if len(z) < min_n or z.iloc[:,0].nunique() < 2 or z.iloc[:,1].nunique() < 2:
        return np.nan
    try: return float(spearmanr(z.iloc[:,0], z.iloc[:,1]).statistic)
    except Exception: return np.nan

